namespace fortis::operations {

// Which native route planes this process composed. main.cpp fills it from
// the services' started() state after every owner started and before the
// catalog is generated; a started service always registers its routes or the
// process exits, so "started" here means "served".
struct NetworkLivePlanes {
  // AddressService: balances, transfers, nfts, insight, tx/:hash, tx/:hash/view
  // and /v1/networks/:network/overview (FORTIS_NATIVE_ADDRESS_CANARY=1).
  bool address = false;
  // TokenService: /v1/networks/:network/token/:tokenId[/page] (price canary).
  bool token = false;
  // NewsService ingest, the only writer of the news the overview reads
  // (FORTIS_NATIVE_NEWS_CANARY=1).
  bool news = false;
  // PriceSpotService (GET /v1/prices) and PriceHistoryService
  // (GET/POST /v1/prices/history, GET /v1/prices/ohlc).
  bool prices_spot = false;
  bool prices_history = false;
};

struct NetworkRouteContext {
  const networks::NativeNetworkRegistry* registry = nullptr;
  const config::ProviderRuntimeConfig* config = nullptr;
  NetworkLivePlanes planes{};
};

// The published value ("ok" or "none", static strings) of every capability
// of every catalogued network, in registry order and kNetworkCapabilityNames
// order. False when `capacity` is below the catalogue size or the chain
// catalog cannot be built for `config`.
bool DeriveNetworkCapabilities(const networks::NativeNetworkRegistry& registry, const config::ProviderRuntimeConfig& config,
                               const NetworkLivePlanes& planes,
                               const char* (*values)[networks::kNetworkCapabilityCount], size_t capacity,
                               size_t* count);

// Builds the JSON and protobuf catalog documents into the caller's buffers.
// False when either does not fit or a field exceeds its nanopb bound.
bool BuildNetworksDocuments(const networks::NativeNetworkRegistry& registry, const config::ProviderRuntimeConfig& config,
                            const NetworkLivePlanes& planes, char* json, size_t json_capacity,
                            size_t* json_out, uint8_t* proto, size_t proto_capacity,
                            size_t* proto_out);

// Generates both documents once and registers GET /v1/networks; false (the
// process refuses to start) when generation fails.
bool RegisterNetworksRoute(http::HttpRouter& router, NetworkRouteContext* context);

// The immutable JSON catalogue generated by RegisterNetworksRoute. The
// operations preview serves these same public network metadata bytes.
const char* NetworkCatalogJson(size_t* length);

}  // namespace fortis::operations
