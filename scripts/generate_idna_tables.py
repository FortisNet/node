#!/usr/bin/env python3
"""Generate src/compat/idna_tables.cpp from the pinned Ada v2.9.2 ada-idna source.

The vendored third_party/ada-idna/v2.9.2/ada_idna.cpp is data: this script
verifies its SHA-256, extracts the literal table initializers Ada's
idna::to_ascii consults (mapping, NFC normalization, bidi directions,
combining marks and the ContextJ joining classes) and writes them as C
arrays. Output is deterministic.

  python3 -I scripts/generate_idna_tables.py           # write
  python3 -I scripts/generate_idna_tables.py --check   # compare only
"""

import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "third_party/ada-idna/v2.9.2/ada_idna.cpp"
OUTPUT = ROOT / "src/compat/idna_tables.cpp"
PINNED = "1b9af936cdb63fb295c61e9444fee89e0b565205f8002fb40425fcaae5d544b7"

# ada::idna::direction, in declaration order (validity.cpp).
DIRECTIONS = ["NONE", "BN", "CS", "ES", "ON", "EN", "L", "R", "NSM", "AL", "AN",
              "ET", "WS", "RLO", "LRO", "PDF", "RLE", "RLI", "FSI", "PDI", "LRI",
              "B", "S", "LRE"]

# (name in Ada, C type, output name, declared shape or None). Two-dimensional
# tables are zero-padded per row and to their declared row count exactly as
# C aggregate initialization does (Ada's canonical_combining_class_block
# lists 66 of its 67 rows).
TABLES = [
    ("mappings", "uint32_t", "kMappings", (5164,)),
    ("table", "uint32_t", "kMappingTable", (8000, 2)),
    ("decomposition_index", "uint8_t", "kDecompositionIndex", (4352,)),
    ("decomposition_block", "uint16_t", "kDecompositionBlock", (67, 257)),
    ("decomposition_data", "uint32_t", "kDecompositionData", (9102,)),
    ("canonical_combining_class_index", "uint8_t", "kCccIndex", (4352,)),
    ("canonical_combining_class_block", "uint8_t", "kCccBlock", (67, 256)),
    ("composition_index", "uint8_t", "kCompositionIndex", (4352,)),
    ("composition_block", "uint16_t", "kCompositionBlock", (67, 257)),
    ("composition_data", "uint32_t", "kCompositionData", (1883,)),
    ("combining", "uint32_t", "kCombining", None),
    ("virama", "uint32_t", "kVirama", None),
    ("R", "uint32_t", "kJoiningR", None),
    ("L", "uint32_t", "kJoiningL", None),
    ("D", "uint32_t", "kJoiningD", None),
]


def initializer(text, name):
    match = re.search(r"\b" + re.escape(name) + r"\s*(?:\[\d*\])+\s*=\s*\{", text)
    if not match:
        raise SystemExit(f"table {name} not found")
    depth = 0
    start = match.end() - 1
    for index in range(start, len(text)):
        char = text[index]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1:index]
    raise SystemExit(f"table {name} is not terminated")


def numbers(body, name):
    body = re.sub(r"//[^\n]*", "", body)
    tokens = re.findall(r"0[xX][0-9a-fA-F]+|\d+|[A-Za-z_][A-Za-z_0-9:]*", body)
    values = []
    for token in tokens:
        if not re.fullmatch(r"0[xX][0-9a-fA-F]+|\d+", token):
            raise SystemExit(f"table {name}: unexpected token {token}")
        values.append(int(token, 0))
    return values


def emit(lines, c_type, out_name, values):
    lines.append(f"extern const {c_type} {out_name}[{len(values)}] = {{")
    for offset in range(0, len(values), 12):
        chunk = ", ".join(str(v) for v in values[offset:offset + 12])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append(f"extern const size_t {out_name}Count = {len(values)};")
    lines.append("")


def generate():
    data = SOURCE.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != PINNED:
        raise SystemExit(f"{SOURCE} hash {digest} does not match the pinned {PINNED}")
    text = data.decode("utf-8")
    lines = [
        "// Generated by scripts/generate_idna_tables.py from",
        "// third_party/ada-idna/v2.9.2/ada_idna.cpp (Ada v2.9.2, ada-idna 2023-09-19,",
        f"// SHA-256 {PINNED}). Do not edit.",
        "#include \"idna.h\"",
        "",
        "namespace fortis::compat::idna_tables {",
        "",
    ]
    for name, c_type, out_name, shape in TABLES:
        body = initializer(text, name)
        if shape is not None and len(shape) == 2:
            rows = re.findall(r"\{([^{}]*)\}", body)
            if len(rows) > shape[0] or body.count("{") != len(rows):
                raise SystemExit(f"table {name}: {len(rows)} rows, declared {shape[0]}")
            values = []
            for row in rows:
                cells = numbers(row, name)
                if len(cells) > shape[1]:
                    raise SystemExit(f"table {name}: row of {len(cells)} > {shape[1]}")
                values.extend(cells + [0] * (shape[1] - len(cells)))
            values.extend([0] * (shape[1] * (shape[0] - len(rows))))
        else:
            values = numbers(body, name)
            if shape is not None:
                if len(values) > shape[0]:
                    raise SystemExit(f"table {name}: {len(values)} values > {shape[0]}")
                values.extend([0] * (shape[0] - len(values)))
        if name in ("combining", "virama", "R", "L", "D") and values != sorted(values):
            raise SystemExit(f"table {name} is not sorted")
        emit(lines, c_type, out_name, values)
    body = initializer(text, "dir_table")
    entries = re.findall(r"\{\s*(0x[0-9a-fA-F]+|\d+)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*,"
                         r"\s*direction::([A-Z]+)\s*\}", body)
    if len(entries) != body.count("{"):
        raise SystemExit("dir_table: unparsed entries")
    flat = []
    for start, final, direction in entries:
        flat.extend([int(start, 0), int(final, 0), DIRECTIONS.index(direction)])
    emit(lines, "uint32_t", "kDirections", flat)
    lines.append("}  // namespace fortis::compat::idna_tables")
    return "\n".join(lines) + "\n"


def main():
    output = generate()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != output:
            print(f"{OUTPUT} is stale; run scripts/generate_idna_tables.py", file=sys.stderr)
            return 1
        print("idna tables up to date")
        return 0
    OUTPUT.write_text(output, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
