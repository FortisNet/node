#!/usr/bin/env python3
"""Embed repository-owned branding and possible features; no runtime file reads."""
import argparse
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ('node-hall.webp', 'fortis-favicon.svg', 'fortisnet-lockup.svg', 'social-preview.jpg')


def outputs():
    raw = (ROOT / 'contracts/node-future-features.json').read_text()
    catalog = json.loads(raw)
    if set(catalog) != {'schemaVersion', 'status', 'notice', 'features'} or type(catalog['schemaVersion']) is not int or catalog['schemaVersion'] != 1 or catalog['status'] != 'possible':
        raise ValueError('Unsupported future-feature catalog')
    if not isinstance(catalog['notice'], str) or not 1 <= len(catalog['notice']) <= 480 or not isinstance(catalog['features'], list) or not 1 <= len(catalog['features']) <= 16:
        raise ValueError('Future-feature notice and bounded list required')
    ids = set()
    for item in catalog['features']:
        if set(item) != {'id', 'name', 'description'} or any(not isinstance(v, str) or not 1 <= len(v) <= 240 for v in item.values()):
            raise ValueError('Invalid future-feature entry')
        if item['id'] in ids or not all(c in 'abcdefghijklmnopqrstuvwxyz0123456789-' for c in item['id']):
            raise ValueError('Future-feature IDs must be unique and URL-safe')
        ids.add(item['id'])
    page = (ROOT / 'assets/node-home.html').read_text()
    page = page.replace('@FUTURE_NOTICE@', html.escape(catalog['notice']))
    page = page.replace('@FUTURE_FEATURES@', ''.join('<li><strong>' + html.escape(f['name']) + '</strong><p>' + html.escape(f['description']) + '</p></li>' for f in catalog['features']))
    before, after = page.split('@SERVICES@')
    if len((before + after).encode()) > 28 * 1024:
        raise ValueError('Rendered home exceeds the 28 KiB static-content budget')
    strings = [('kNodeHomeBeforeServices', before), ('kNodeHomeAfterServices', after), ('kNodeFutureFeaturesJson', raw)]
    generated = '// Generated by scripts/generate_node_home.py; edit assets/node-home.html or contracts/node-future-features.json.\n'
    for name, text in strings:
        if ')FHOME"' in text:
            raise ValueError('Raw-string delimiter collision')
        generated += f'const char {name}[] = R"FHOME({text})FHOME";\n'
    arrays = '// Generated by scripts/generate_node_home.py; assets are embedded verbatim.\n'
    for index, asset in enumerate(ASSETS):
        data = (ROOT / 'assets' / asset).read_bytes()
        if not data or len(data) > 256 * 1024:
            raise ValueError('Brand asset must be nonempty and <=256 KiB')
        arrays += f'const uint8_t kNodeAsset{index}[] = {{\n'
        arrays += '\n'.join('  ' + ','.join(str(b) for b in data[i:i+24]) + ',' for i in range(0, len(data), 24)) + '\n};\n'
    return {ROOT / 'src/operations/node_home.inc': generated, ROOT / 'src/operations/node_assets.inc': arrays}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.write:
            path.write_text(text)
        elif not path.exists() or path.read_text() != text:
            raise SystemExit(f'Stale generated file: {path.relative_to(ROOT)}; run make generate-node-home')
    print('Node homepage and brand assets are current')


if __name__ == '__main__':
    main()
