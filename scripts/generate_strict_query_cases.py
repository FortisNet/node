#!/usr/bin/env python3
"""Generate explicit query-case deltas from frozen inputs, using Python's
UTF-8 decoder and urllib (independent of the C++ implementation). Does not
change any fixture or compute provider responses. Inspect the generated rows.
"""
import json
import re
from pathlib import Path
from urllib.parse import unquote_to_bytes

ROOT = Path(__file__).resolve().parents[1]


def first_values(target):
    result, repeated = {}, set()
    for pair in target.partition('?')[2].split('&'):
        if re.search(r'%(?![a-fA-F0-9]{2})', pair):
            raise ValueError('invalid escape')
        key, _, value = pair.partition('=')
        key = unquote_to_bytes(key.replace('+', ' ')).decode('utf-8')
        value = unquote_to_bytes(value.replace('+', ' ')).decode('utf-8')
        if key in result:
            repeated.add(key)
        else:
            result[key] = value
    return result, repeated


def price_cases():
    rows = []
    for suite in ('spot', 'history', 'ohlc'):
        fixture = json.loads((ROOT / f'tests/corpus/price_{suite}_query_route.json').read_text())
        for group in fixture['groups']:
            if group['name'] == 'auth':
                continue
            for case in group['cases']:
                urls = [case['url']] if 'url' in case else case['urls']
                # These contract-changing query cases each have one target.
                if len(urls) != 1:
                    continue
                target = urls[0]
                try:
                    values, repeated = first_values(target)
                    numbers = {'spot': (), 'history': ('from', 'to'), 'ohlc': ('days',)}[suite]
                    reject = any(k in values and re.fullmatch('[0-9]+', values[k]) is None for k in numbers)
                except (ValueError, UnicodeError):
                    reject, values, repeated = True, {}, set()
                if reject:
                    rows.append({'suite': suite, 'group': group['name'], 'name': case['name'], 'accept': False})
                elif repeated & {'ids', 'id', 'fiat', 'from', 'to', 'interval', 'days'}:
                    # Only schema-valid first occurrences become successful.
                    if suite == 'spot' and not re.fullmatch('[a-z]{3,5}', values.get('fiat', 'usd')):
                        continue
                    rows.append({'suite': suite, 'group': group['name'], 'name': case['name'],
                                 'accept': True, 'values': values})
    return rows


def main():
    rows = price_cases()
    (ROOT / 'tests/fixtures/strict_price_query_cases.json').write_text(json.dumps(rows, indent=2)+'\n')
    out = ['// Generated by scripts/generate_strict_query_cases.py.',
           '// Explicit deltas only. All other frozen fixture assertions remain.',
           '#pragma once', '#include <string.h>', 'namespace strict {',
           'struct PriceCase { const char* suite; const char* group; const char* name;',
           '  const char* id; const char* fiat; long long from; long long to; const char* interval; int days; bool accept; };',
           'inline const PriceCase* Price(const char* suite, const char* group, const char* name) {',
           '  static const PriceCase rows[] = {']
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    for row in rows:
        v = row.get('values', {})
        fields = [quote(row[k]) for k in ('suite', 'group', 'name')]
        fields += [quote(v.get('id', v.get('ids', ''))), quote(v.get('fiat', 'usd')),
                   v.get('from', '0'), v.get('to', '0'), quote(v.get('interval', '1h')), v.get('days', '0'), str(row['accept']).lower()]
        out.append('    {'+', '.join(fields)+'},')
    out += ['  };', '  for (const auto& row : rows)',
            '    if (!strcmp(row.suite, suite) && !strcmp(row.group, group) && !strcmp(row.name, name)) return &row;',
            '  return nullptr;', '}', '}  // namespace strict', '']
    (ROOT / 'tests/strict_price_query_cases.h').write_text('\n'.join(out))
    print(f'{len(rows)} explicit price query deltas')


if __name__ == '__main__':
    main()
