#!/usr/bin/env node
// Generate native-owned redaction tables from contracts/ and pinned Unicode data.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const redactionPath = path.join(scriptDir, '../contracts/redaction-data.json');
const wordlistPath = path.join(scriptDir, '../contracts/bip39-english.json');
const outputPath = path.join(repoRoot, 'src/compat/redaction_tables.cpp');

function ranges(set) {
  const out = [];
  for (const cp of set) {
    const last = out[out.length - 1];
    if (last && last[1] + 1 === cp) last[1] = cp;
    else out.push([cp, cp]);
  }
  return out;
}

function readRules(source) {
  const rules = JSON.parse(source);
  if (typeof rules.placeholder !== 'string' || !rules.placeholder ||
      !Array.isArray(rules.invisible) || !Array.isArray(rules.confusables))
    throw new Error('invalid native redaction data');
  let previous = -1;
  for (const cp of rules.invisible) {
    if (!Number.isInteger(cp) || cp <= previous || cp > 0xffff)
      throw new Error('invisible code points must be sorted, unique BMP integers');
    previous = cp;
  }
  previous = -1;
  for (const [from, to] of rules.confusables) {
    if (!Number.isInteger(from) || from <= previous || from > 0x10ffff ||
        !Number.isInteger(to) || !/^[A-Za-z]$/.test(String.fromCharCode(to)))
      throw new Error('invalid confusable mapping');
    previous = from;
  }
  return rules;
}

function readWordlist(source) {
  const words = JSON.parse(source);
  if (!Array.isArray(words) || words.length !== 2048 ||
      words.some((word, i) => !/^[a-z]{3,8}$/.test(word) || (i && words[i-1] >= word)))
    throw new Error('BIP-39 wordlist must contain 2048 sorted, unique words');
  return words;
}

function isSurrogate(cp) { return cp >= 0xd800 && cp <= 0xdfff; }
function isHangulSyllable(cp) { return cp >= 0xac00 && cp <= 0xd7a3; }

// Canonical combining classes are not exposed by JavaScript, but their order
// is observable: NFD swaps two adjacent marks exactly when the first has the
// higher class. A code point is a non-starter when it reorders against
// U+0334 (class 1) or U+0301 (class 230). Ranks keep the order and the
// equalities of the real classes, which is all reordering and composition
// blocking compare.
function combiningRanks() {
  const marks = [];
  for (let cp = 0; cp <= 0x10ffff; cp += 1) {
    if (isSurrogate(cp)) continue;
    const mark = String.fromCodePoint(cp);
    if (mark.normalize('NFD') !== mark) continue;
    if (`a${mark}\u0334`.normalize('NFD') === `a\u0334${mark}` ||
        `a\u0301${mark}`.normalize('NFD') === `a${mark}\u0301`) marks.push(mark);
  }
  const after = (x, y) => `a${x}${y}`.normalize('NFD') === `a${y}${x}`;
  const compare = (x, y) => (after(x, y) ? 1 : after(y, x) ? -1 : 0);
  marks.sort((x, y) => compare(x, y) || x.codePointAt(0) - y.codePointAt(0));
  const ranks = [];
  let rank = 0;
  for (let i = 0; i < marks.length; i += 1) {
    if (i === 0 || compare(marks[i - 1], marks[i]) !== 0) rank += 1;
    ranks.push([marks[i].codePointAt(0), rank]);
  }
  if (rank > 255) throw new Error('more combining classes than a byte holds');
  return ranks.sort((a, b) => a[0] - b[0]);
}

function normalizationTables() {
  const map = [];
  const pairs = [];
  for (let cp = 0; cp <= 0x10ffff; cp += 1) {
    if (isSurrogate(cp)) continue;
    const single = String.fromCodePoint(cp);
    // Hangul syllables decompose and compose arithmetically in the native code.
    const nfkd = isHangulSyllable(cp) ? single : single.normalize('NFKD');
    if (nfkd !== single) map.push([cp, [...nfkd].map((char) => char.codePointAt(0))]);
    // Canonical composition pairs: a primary composite is its own NFC and has
    // a two-code-point single-level canonical decomposition. Hangul
    // syllables compose algorithmically in the native code.
    if (isHangulSyllable(cp) || single.normalize('NFC') !== single) continue;
    const nfd = [...single.normalize('NFD')];
    if (nfd.length < 2) continue;
    const second = nfd[nfd.length - 1];
    const first = nfd.slice(0, -1).join('').normalize('NFC');
    if ([...first].length !== 1 || (first + second).normalize('NFC') !== single) continue;
    pairs.push([first.codePointAt(0), second.codePointAt(0), cp]);
  }
  pairs.sort((a, b) => (a[0] - b[0]) || (a[1] - b[1]));
  return { map, pairs, ranks: combiningRanks() };
}

function hex(cp) { return `0x${cp.toString(16).toUpperCase().padStart(4, '0')}`; }

function cppString(text) {
  return JSON.stringify(text).replace(/[\u0080-￿]/g, (char) =>
    [...Buffer.from(char, 'utf8')].map((byte) => `\\x${byte.toString(16)}`).join('') + '""');
}

function render(words, rules, tables) {
  let out = '// Generated by scripts/generate_redaction_tables.mjs from\n';
  out += '// contracts/redaction-data.json, bip39-english.json and the\n';
  out += `// Unicode ${process.versions.unicode} normalization data of Node.js (ICU ${process.versions.icu}).\n`;
  out += '// Do not edit; run make generate-redaction-tables.\n';
  out += '#include "redaction_tables.h"\n\n';
  out += 'namespace fortis::compat {\n\n';
  out += `const char kRedactionUnicodeVersion[] = ${JSON.stringify(process.versions.unicode)};\n`;
  out += `const char kRedactionPlaceholder[] = ${cppString(rules.placeholder)};\n\n`;
  out += 'const char* const kBip39English[2048] = {\n';
  for (let i = 0; i < words.length; i += 8) {
    out += `  ${words.slice(i, i + 8).map((word) => `"${word}"`).join(', ')},\n`;
  }
  out += '};\n\n';
  out += 'const RedactionRange kRedactionInvisible[] = {\n';
  for (const [from, to] of ranges(rules.invisible)) out += `  {${hex(from)}, ${hex(to)}},\n`;
  out += '};\n';
  out += 'const size_t kRedactionInvisibleCount = sizeof(kRedactionInvisible) / sizeof(kRedactionInvisible[0]);\n\n';
  out += 'const RedactionConfusable kRedactionConfusables[] = {\n';
  for (const [from, to] of rules.confusables) out += `  {${hex(from)}, '${String.fromCharCode(to)}'},\n`;
  out += '};\n';
  out += 'const size_t kRedactionConfusableCount = sizeof(kRedactionConfusables) / sizeof(kRedactionConfusables[0]);\n\n';
  const pool = [];
  out += 'const NfkdMapping kNfkdMappings[] = {\n';
  for (const [cp, mapped] of tables.map) {
    out += `  {${hex(cp)}, ${pool.length}U, ${mapped.length}U},\n`;
    pool.push(...mapped);
  }
  if (pool.length > 0xffff) throw new Error('NFKD pool exceeds a 16-bit offset');
  out += '};\n';
  out += 'const size_t kNfkdMappingCount = sizeof(kNfkdMappings) / sizeof(kNfkdMappings[0]);\n';
  out += 'const uint32_t kNfkdPool[] = {\n';
  for (let i = 0; i < pool.length; i += 10) {
    out += `  ${pool.slice(i, i + 10).map(hex).join(', ')},\n`;
  }
  out += '};\n\n';
  out += 'const CompositionPair kCompositionPairs[] = {\n';
  for (const [first, second, composite] of tables.pairs) {
    out += `  {${hex(first)}, ${hex(second)}, ${hex(composite)}},\n`;
  }
  out += '};\n';
  out += 'const size_t kCompositionPairCount = sizeof(kCompositionPairs) / sizeof(kCompositionPairs[0]);\n\n';
  out += 'const CombiningRank kCombiningRanks[] = {\n';
  for (let i = 0; i < tables.ranks.length; i += 6) {
    out += `  ${tables.ranks.slice(i, i + 6).map(([cp, rank]) => `{${hex(cp)}, ${rank}}`).join(', ')},\n`;
  }
  out += '};\n';
  out += 'const size_t kCombiningRankCount = sizeof(kCombiningRanks) / sizeof(kCombiningRanks[0]);\n\n';
  const digest = createHash('sha256').update(JSON.stringify(rules)).digest('hex');
  out += `// SHA-256 of native-owned redaction data.\n`;
  out += `const char kRedactionRulesSha256[] = "${digest}";\n\n`;
  out += '}  // namespace fortis::compat\n';
  return out;
}

// The ICU build version is provenance, not table content. Homebrew and the
// official Node image can ship identical Unicode data with different ICU patch
// versions. Compare every actual table byte and the Unicode version as before.
export function sameGeneratedTables(current, generated) {
  const normalize = text => text.replace(
    /^(\/\/ Unicode [0-9.]+ normalization data of Node\.js) \(ICU [0-9.]+\)\.$/m,
    '$1.');
  return normalize(current) === normalize(generated);
}

async function main() {
  const mode = process.argv[2];
  if (mode !== '--write' && mode !== '--check')
    throw new Error('usage: node scripts/generate_redaction_tables.mjs --write|--check');
  const words = readWordlist(await readFile(wordlistPath, 'utf8'));
  const rules = readRules(await readFile(redactionPath, 'utf8'));
  const generated = render(words, rules, normalizationTables());
  if (mode === '--write') {
    await writeFile(outputPath, generated);
    process.stdout.write(`generated ${path.relative(repoRoot, outputPath)}\n`);
    return;
  }
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (!sameGeneratedTables(current, generated)) {
    const recorded = /Unicode (\S+) normalization data/.exec(current)?.[1];
    if (recorded && recorded !== process.versions.unicode) {
      process.stderr.write(`redaction tables were generated with Unicode ${recorded}; ` +
        `this Node.js has ${process.versions.unicode}\n`);
    }
    process.stderr.write('native redaction tables are stale; run make generate-redaction-tables\n');
    process.exitCode = 1;
    return;
  }
  process.stdout.write('native redaction tables match native contracts\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => { console.error(error.message); process.exitCode = 1; });
}
