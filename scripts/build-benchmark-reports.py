#!/usr/bin/env python3
"""Generate the public benchmark page data from reviewed aggregate JSONL files."""
import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--run", action="append", nargs=2, metavar=("LABEL", "FILE"), required=True)
args = parser.parse_args()
published = []
for label, filename in args.run:
    source = Path(filename)
    if source.stat().st_size > 128 * 1024:
        parser.error(f"{source} exceeds the published report size limit")
    records = [json.loads(line) for line in source.read_text().splitlines() if line.strip()]
    if not records or len(records) > 250 or any(not isinstance(row, dict) for row in records):
        parser.error(f"{source} must contain 1–250 JSON objects")
    if not isinstance(records[0].get("environment"), str):
        parser.error(f"{source} must begin with its benchmark environment")
    published.append({"label": label, "records": records})
data = json.dumps(published, ensure_ascii=True, separators=(",", ":"), allow_nan=False)
# JSON script blocks are parsed as raw text. Keep every markup delimiter and
# the C++ raw-string delimiter out of the encoded report.
data = data.replace("<", r"\u003c").replace(">", r"\u003e").replace(")", r"\u0029")
# Separate literals keep each source literal below the C++ minimum bound.
print("// Generated by scripts/build-benchmark-reports.py from reviewed aggregate output.")
for i in range(0, len(data), 2048):
    print('R"REPORT(' + data[i:i + 2048] + ')REPORT"')
