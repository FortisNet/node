#!/usr/bin/env node
// Generates src/compat/js_case_tables.cpp: the data the native port needs to apply
// JavaScript's locale-independent String.prototype.toUpperCase and
// toLowerCase exactly as the TypeScript service does:
//   - every code point whose single-character upper/lower mapping differs
//     from itself, with its full (possibly multi-code-point) mapping;
//   - the Cased and Case_Ignorable code point ranges, which the Final_Sigma
//     rule of toLowerCase consults for U+03A3.
// Everything is derived from this Node.js runtime's ICU data. The table is
// tied to the Unicode version the TypeScript service runs on; --check reports
// a different Node.js Unicode version as drift.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const outputPath = path.resolve(scriptDir, '../../src/compat/js_case_tables.cpp');

function mappings(method) {
  const rows = [];
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const input = String.fromCodePoint(cp);
    const output = input[method]();
    if (output === input) continue;
    const points = [...output].map((value) => value.codePointAt(0));
    if (points.length > 3) throw new Error(`${method} of U+${cp.toString(16)} has ${points.length} code points`);
    rows.push([cp, points]);
  }
  return rows;
}

function ranges(regex) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const member = cp <= 0x10ffff && !(cp >= 0xd800 && cp <= 0xdfff) &&
      regex.test(String.fromCodePoint(cp));
    if (member && start < 0) start = cp;
    if (!member && start >= 0) {
      // Surrogates are never members; keep ranges that straddle them split.
      out.push([start, cp - 1]);
      start = -1;
    }
  }
  return out;
}

function hex(value) { return `0x${value.toString(16)}`; }

function mappingTable(name, rows) {
  const lines = rows.map(([cp, points]) => {
    const padded = [...points, 0, 0].slice(0, 3);
    return `  {${hex(cp)}, ${points.length}, {${padded.map(hex).join(', ')}}},`;
  });
  return `const JsCaseMapping ${name}[] = {\n${lines.join('\n')}\n};\n` +
    `const size_t ${name}Count = sizeof(${name}) / sizeof(${name}[0]);\n`;
}

function rangeTable(name, rows) {
  const lines = rows.map(([first, last]) => `  {${hex(first)}, ${hex(last)}},`);
  return `const JsCodePointRange ${name}[] = {\n${lines.join('\n')}\n};\n` +
    `const size_t ${name}Count = sizeof(${name}) / sizeof(${name}[0]);\n`;
}

function generate() {
  // The Final_Sigma rule is the only context-sensitive mapping JavaScript
  // applies without a locale; the native code implements it by hand.
  if ('AΣ'.toLowerCase() !== 'aς' || 'Σ'.toLowerCase() !== 'σ') {
    throw new Error('this runtime does not apply Final_Sigma as the native port assumes');
  }
  const upper = mappings('toUpperCase');
  const lower = mappings('toLowerCase');
  const cased = ranges(/\p{Cased}/u);
  const ignorable = ranges(/\p{Case_Ignorable}/u);
  return `// Generated by tests/reference/generate_js_case_tables.mjs. Do not edit.
// Node.js ${process.versions.node}, Unicode ${process.versions.unicode}.
#include "js_case.h"

namespace fortis::compat::js_case_tables {

const char kUnicodeVersion[] = "${process.versions.unicode}";

${mappingTable('kUpper', upper)}
${mappingTable('kLower', lower)}
${rangeTable('kCased', cased)}
${rangeTable('kCaseIgnorable', ignorable)}
}  // namespace fortis::compat::js_case_tables
`;
}

const mode = process.argv[2];
const text = generate();
if (mode === '--write') {
  await writeFile(outputPath, text);
} else if (mode === '--check') {
  const saved = await readFile(outputPath, 'utf8').catch(() => '');
  const version = /Unicode ([0-9.]+)\./.exec(saved)?.[1];
  // The header names the Node.js patch version; only the data must match.
  const body = (value) => value.split('\n').slice(2).join('\n');
  if (body(saved) !== body(text)) {
    console.error(version !== process.versions.unicode
      ? `js_case_tables.cpp was generated for Unicode ${version}; this Node.js has ${process.versions.unicode}`
      : 'src/compat/js_case_tables.cpp is stale: run this tool with --write');
    process.exit(1);
  }
} else {
  console.error('usage: generate_js_case_tables.mjs --write|--check');
  process.exit(2);
}
